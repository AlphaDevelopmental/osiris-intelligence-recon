#!/usr/bin/env python3
"""Generate docs/ENDPOINT_REGISTRY.md from osiris/registry.py and docs/live_verification.json."""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from osiris import registry as reg  # noqa: E402


def verification(entry: dict) -> str:
    if not entry:
        return "source-verified; not live-probed"
    if entry.get("not_probed"):
        return f"source-verified; not live-probed ({entry['not_probed']})"
    probes = entry.get("probes") or []
    if not probes:
        return "source-verified; not live-probed"
    parts = []
    for p in probes:
        label = ",".join(f"{k}={v}" for k, v in (p.get("params") or {}).items()) or p.get("probe", "")
        st, http = p.get("status"), p.get("http")
        if p.get("probe", "").startswith("config-check") and "Missing target" in p.get("error", ""):
            parts.append(f"LIVE ✔ configured: target-less probe → {http} `Missing target parameter` (no scan sent)")
        elif p.get("probe", "").startswith("config-check") and http == 503:
            parts.append("LIVE ◐ reachable, scanner not configured (503)")
        elif st == "success" and p.get("content_type", "").startswith("text/event-stream"):
            parts.append(f"LIVE ✔ stream opened ({http}, text/event-stream)")
        elif st == "success" and p.get("documented_keys_missing"):
            parts.append(f"LIVE ◐ {label}: {http}, degraded — missing {', '.join(p['documented_keys_missing'])}")
        elif st == "success":
            parts.append(f"LIVE ✔ {label}: {http}")
        elif st == "oversized":
            parts.append(f"LIVE ◐ {label}: {http}, body exceeded probe size limit")
        else:
            parts.append(f"LIVE ✘ {label}: {st} {http or ''} {p.get('error', '')[:90]}".strip())
    return "<br>".join(parts)


def main() -> int:
    live_path = ROOT / "docs" / "live_verification.json"
    live = json.loads(live_path.read_text()) if live_path.exists() else {"results": {}}
    res = live.get("results", {})
    out = [
        "# OSIRIS Endpoint Registry",
        "",
        "Generated by `tools/build_registry_doc.py` from `osiris/registry.py` and `docs/live_verification.json`. "
        "Do not edit by hand.",
        "",
        f"- Upstream source reviewed: [{reg.UPSTREAM_REPO}]({reg.UPSTREAM_REPO}) at commit `{reg.UPSTREAM_COMMIT}`",
        f"- Live probes: `{live.get('base', 'n/a')}` at `{live.get('verified_at', 'never')}`",
        f"- Registered operations: **{len(reg.ENDPOINTS)}** (the published docs catalog, `src/app/docs/apiCatalog.ts`)",
        "",
        "## How each entry was verified",
        "",
        "* **source-verified** — every one of the 71 entries: parameter names, HTTP method and behaviour were read "
        "from the route handler (`src/app/api/**/route.ts`), not inferred from the docs.",
        "* **LIVE ✔** — called on the public deployment with the docs' example (or a neutral) input and returned 2xx JSON.",
        "* **LIVE ◐** — reachable and 2xx, but some documented keys were absent (an upstream data source the "
        "OSIRIS server depends on failed or the body was larger than the probe limit).",
        "* **LIVE ✘** — the probe failed; the error is shown. This is a statement about that moment, not the route.",
        "* **not live-probed** — deliberately not called (state-changing, paid, streaming with an id, personal "
        "data, or would make OSIRIS contact an arbitrary host).",
        "",
        "Categories: `target-osint` (takes a target-derived subject), `global-feed`, `system`, `requires-context` "
        "(needs coordinates/ids/URLs), `stream`, `state-changing`, `ai`, `active`, `caller-specific`.  ",
        "Target contact: `none` = the target receives nothing; `indirect` = the OSIRIS server contacts the target; "
        "`active` = a scanner contacts the target.",
        "",
        "## Rate limits (from `src/lib/ssrf-guard.ts`)",
        "",
        "Most OSINT routes call `isRateLimited(clientIp, N)` with the **same key**, so dns, certs, whois, ip, bgp, "
        "threats, sanctions, cve, entity/expand, scanner, arcgis and ai/overview share one fixed 60-second counter "
        "per client IP per server instance; each route compares the shared count with its own threshold (20, or "
        "30 for cve/entity/arcgis, 5 for scanner). This was observed live: after a burst of OSINT calls, "
        "`/api/scanner` answered 429. The client budgets 18 calls/min for this bucket.",
        "",
        "## Registry",
        "",
        "| # | Method | Path | Category | Params (* = required) | Target inputs | Contact | Rate limit | "
        "Auth / server config | Modes | Verification |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for n, e in enumerate(reg.ENDPOINTS, 1):
        params = ", ".join(f"`{p.name}`{'*' if p.required else ''}" for p in e.params) or "—"
        auth = e.auth if e.auth != "none" else ""
        cfg = "; ".join(x for x in (auth, ", ".join(e.server_config)) if x) or "—"
        out.append(
            f"| {n} | {e.method} | `{e.path}` | {e.category} | {params} | {', '.join(e.inputs) or '—'} | "
            f"{e.contact} | {e.rate_limit} | {cfg} | {', '.join(sorted(e.modes)) or '—'} | "
            f"{verification(res.get(e.key, {}))} |"
        )
    out += ["", "## Corrections and documentation discrepancies", ""]
    for e in reg.ENDPOINTS:
        if e.docs_discrepancy or e.notes:
            out.append(f"- **`{e.key}`** — {' '.join(x for x in (e.docs_discrepancy, e.notes) if x)}")
    out += [
        "",
        "## Previous client parameters, replayed live",
        "",
        "The earlier script's parameter names were sent once each to confirm the discrepancy:",
        "",
        "| Endpoint | Old params | Result |",
        "|---|---|---|",
    ]
    for key, entry in res.items():
        lp = entry.get("legacy_param_probe")
        if lp:
            detail = lp.get("error") or ("keys: " + ", ".join(lp.get("keys") or []))
            out.append(f"| `{key}` | `{json.dumps(lp['params'])}` | {lp['status']} {lp.get('http') or ''} — {detail} |")
    out += [
        "",
        "## Upstream routes not in the published catalog",
        "",
        "Present in the source tree but not part of the 71 documented operations; not registered or called:",
        "",
        ", ".join(f"`{p}`" for p in reg.UNDOCUMENTED_ROUTES),
        "",
        "## Totals",
        "",
    ]
    live_ok = sum(1 for e in reg.ENDPOINTS if "LIVE ✔" in verification(res.get(e.key, {})))
    live_part = sum(
        1
        for e in reg.ENDPOINTS
        if "LIVE ◐" in verification(res.get(e.key, {})) and "LIVE ✔" not in verification(res.get(e.key, {}))
    )
    failed = sum(
        1
        for e in reg.ENDPOINTS
        if "LIVE ✘" in verification(res.get(e.key, {}))
        and not any(s in verification(res.get(e.key, {})) for s in ("LIVE ✔", "LIVE ◐"))
    )
    out += [
        f"- Source-verified: {len(reg.ENDPOINTS)}",
        f"- Live-verified (a clean 2xx, or for /api/scanner the expected target-less configuration answer): {live_ok}",
        f"- Live-reached but degraded only: {live_part}",
        f"- Live probe failed only: {failed}",
        f"- Not live-probed (provisional at runtime): {len(reg.ENDPOINTS) - live_ok - live_part - failed}",
        "",
    ]
    (ROOT / "docs" / "ENDPOINT_REGISTRY.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote docs/ENDPOINT_REGISTRY.md", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
